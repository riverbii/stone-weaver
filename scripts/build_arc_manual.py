def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default="data/db/stone.db")
    args = ap.parse_args()

    beats = [
        Beat(
            scene=scene,
            goal=goal,
            characters=chars,
            constraints=constraints,
            expected_out=expected,
        )
        for _, scene, goal, chars, constraints, expected in MANUAL_BEATS
    ]
    arc = Arc(
        name="癸酉本后28回情节弧·人工骨架",
        version="guihui_manual",
        beats=beats,
        source_chapter_range="81-108",
    )
    db = make_session(args.db)
    aid = save_arc(db, arc)
    print(f"✅ 人工情节弧已入库（arc id={aid}，{len(beats)} beat）")
    print(f"   name: {arc.name}")
    print(f"   range: {arc.source_chapter_range}")
    db.close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
